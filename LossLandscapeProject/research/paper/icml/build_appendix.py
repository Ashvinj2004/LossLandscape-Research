"""Generate appendix_full.tex for the ICML version from the long paper (../main.tex).

The appendix holds the long version's results sections verbatim ("Extended results"), minus the figures
and tables that the 8-page main text already shows, followed by the long version's appendices. Section
labels of the copied results sections get the suffix "-full"; references to sections that also exist in
the ICML main text keep pointing there. Copying instead of retyping keeps every number identical to the
verified long version.

usage: python build_appendix.py   (run from paper/icml/)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
LONG = os.path.join(HERE, "..", "main.tex")
MAIN = os.path.join(HERE, "main_icml.tex")
OUT = os.path.join(HERE, "appendix_full.tex")


def labels(tex):
    return set(re.findall(r"\\label\{([^}]*)\}", tex))


def main():
    long_tex = open(LONG, encoding="utf-8").read()
    main_labels = labels(open(MAIN, encoding="utf-8").read())
    results = long_tex[long_tex.index("\\subsection{Adam drifts along the orbit"):long_tex.index("\\section{Discussion and limitations}")]
    appendix = long_tex[long_tex.index("\\appendix") + len("\\appendix"):long_tex.index("\\end{document}")]

    # drop float environments whose label is already shown in the main text
    def drop_shown(m):
        body = m.group(0)
        lab = re.search(r"\\label\{([^}]*)\}", body)
        return "" if lab and lab.group(1) in main_labels else body
    results = re.sub(r"\\begin\{(figure\*?|table)\}.*?\\end\{\1\}\n?", drop_shown, results, flags=re.S)

    # section labels of the copied results get a -full suffix; references follow, unless the main text
    # defines the same section label (then the reference points to the main text)
    sec_labels = re.findall(r"\\label\{(sec:[^}]*)\}", results)
    for lab in sec_labels:
        results = results.replace(f"\\label{{{lab}}}", f"\\label{{{lab}-full}}")
    for lab in sec_labels:
        if lab not in main_labels:
            results = results.replace(f"\\ref{{{lab}}}", f"\\ref{{{lab}-full}}")

    header = ("% generated by build_appendix.py from ../main.tex -- do not edit by hand\n"
              "\\section{Extended results}\\label{app:extended}\n"
              "This appendix reproduces the complete results sections of the long version of this paper, "
              "with every number, control and caveat; figures and tables already shown in the main text are "
              "not repeated.\n\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(header + results + "\n" + appendix)
    print(f"wrote {OUT}: {len(results.split())} + {len(appendix.split())} words; "
          f"{len(sec_labels)} section labels renamed")


if __name__ == "__main__":
    main()
